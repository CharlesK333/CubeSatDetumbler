import numpy as np
import matplotlib.pyplot as plt

mu = 3.99e14
Re = 6371e3

dt = 0.1
t_max = 15000
steps = int(t_max/ dt)

I = np.diag([0.074, 0.14, 0.19])
I_inv = np.linalg.inv(I)

k_bdot = 2e5
k_p = 4e-4
k_d = 2e-2

m_x_max = 0.23
m_y_max = 0.23
m_z_max = 0.34

sigma_B = 5e-6
sigma_w = 0.02
num_sim = 3

def norm(v):
    return np.linalg.norm(v)

def cross(a, b):
    return np.cross(a, b)

def quat_to_R(q):
    q0,q1,q2,q3 = q
    return np.array([
        [1-2*(q2**2+q3**2), 2*(q1*q2 - q0*q3), 2*(q1*q3 + q0*q2)],
        [2*(q1*q2 + q0*q3), 1-2*(q1**2+q3**2), 2*(q2*q3 - q0*q1)],
        [2*(q1*q3 - q0*q2), 2*(q2*q3 + q0*q1), 1-2*(q1**2+q2**2)]
    ])

def Omega(w):
    wx,wy,wz = w
    return np.array([
        [0, -wx, -wy, -wz],
        [wx, 0, wz, -wy],
        [wy, -wz, 0, wx],
        [wz, wy, -wx, 0]
    ])

mE = np.array([0.2e15, 0.1e15, 7.96e15])

def B_field(r):
    r_norm = norm(r)
    r_hat = r / r_norm
    return (1/r_norm**3) * (3 * np.dot(mE, r_hat) * r_hat - mE)


def saturate_m(m):

    scale = min(
        1,
        m_x_max / abs(m[0]) if abs(m[0]) > 1e-8 else 1,
        m_y_max / abs(m[1]) if abs(m[1]) > 1e-8 else 1,
        m_z_max / abs(m[2]) if abs(m[2]) > 1e-8 else 1
    )

    return m * scale

def control_law(r, q, omega, B_body):

  n_orbit = np.sqrt(mu / (norm(r)**3))

  if norm(omega) > 0.05:
        m = k_bdot * cross(omega, B_body)

  else:
      R = quat_to_R(q)
      d_body = R.T @ (r / norm(r))

      ez = np.array([0,0,1])
      e = cross(d_body, ez)

      omega_target = np.array([0, -n_orbit, 0])
      omega_error = omega - omega_target

      tau_des = -k_p * e - k_d * omega_error

      B_norm_sq = np.dot(B_body, B_body) + 1e-10
      m = cross(B_body, tau_des) / B_norm_sq

  return saturate_m(m)

def dynamics(r, v, q, omega, m):

    R = quat_to_R(q)

    B_eci = B_field(r)
    B_body = R.T @ B_eci
    tau = cross(m, B_body)

    r_dot = v
    v_dot = -mu * r / norm(r)**3

    omega_dot = I_inv @ (tau - cross(omega, I @ omega))
    q_dot = 0.5 * Omega(omega) @ q

    return r_dot, v_dot, q_dot, omega_dot

def rk4_step(r, v, q, omega, m):

    r1,v1,q1,w1 = dynamics(r,v,q,omega, m)
    r2,v2,q2,w2 = dynamics(r + 0.5 * dt * r1, v + 0.5 * dt * v1, q + 0.5 * dt * q1, omega + 0.5 * dt * w1, m)
    r3,v3,q3,w3 = dynamics(r + 0.5 * dt * r2, v + 0.5 * dt * v2, q + 0.5 * dt * q2, omega + 0.5 * dt * w2, m)
    r4,v4,q4,w4 = dynamics(r + dt * r3, v+dt * v3, q + dt * q3, omega + dt * w3, m)

    r_new = r + dt/6*(r1 + 2 * r2 + 2 * r3 + r4)
    v_new = v + dt/6*(v1 + 2 * v2 + 2 * v3 + v4)
    q_new = q + dt/6*(q1 + 2 * q2 + 2 * q3 + q4)
    omega_new = omega + dt/6 * (w1 + 2 * w2 + 2 * w3 + w4)

    q_new = q_new / norm(q_new)

    return r_new, v_new, q_new, omega_new

time = [i * dt for i in range(steps)]
all_omega_m = []

print(f"starting {num_sim} MonteCarlo SDE solver")

for sim in range(num_sim):

  r = np.array([Re + 500e3, 0, 0])
  v = np.array([0, 5445, 5445])
  q = np.array([1.0, 0, 0, 0])
  omega = np.array([0.5, -0.3, 0.2])

  run_omega_m = []

  for i in range(steps):

    R_true = quat_to_R(q)
    B_body_true = R_true.T @ B_field(r)

    B_measured = B_body_true + np.random.normal(0, sigma_B, 3)
    omega_measured = omega + np.random.normal(0, sigma_w, 3)

    m_command = control_law(r, q, omega_measured, B_measured)

    r, v, q, omega = rk4_step(r, v, q, omega, m_command)

    run_omega_m.append(norm(omega))

  all_omega_m.append(run_omega_m)
  print(f"Completed {sim + 1} / {num_sim}")

plt.figure(figsize = (10, 8))

colors = plt.cm.viridis(np.linspace(0, 1, num_sim))

for idx, run_data in enumerate(all_omega_m):
  plt.plot(time, run_data, color = colors[idx], alpha = 1, linewidth = 0.1)

plt.title(f"Monte Carlo detumble analysis ({num_sim}) runs with noise")
plt.ylabel("True angular velocity magnitudes (rad/s)")
plt.xlabel("Time (s)")
plt.axhline(0.05, color='black', linestyle='--', label='Mode Switch Threshold (0.05 rad/s)')
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.show()

def compute_power(m):

    Px_max = 0.625
    Py_max = 0.625
    Pz_max = 0.900

    mx_max = 0.40
    my_max = 0.40
    mz_max = 0.50

    Px = Px_max * (m[0] / mx_max)**2
    Py = Py_max * (m[1] / my_max)**2
    Pz = Pz_max * (m[2] / mz_max)**2

    return Px + Py + Pz

energy = 0
power_history = []
time = []

for i in range(steps):

  t = i * dt

  m_command = control_law(r, q, omega_measured, B_measured)

  r, v, q, omega = rk4_step(r, v, q, omega, m_command)

  R = quat_to_R(q)
  B_body = R.T @ B_field(r)
  m = control_law(r, q, omega, B_body)

  P = compute_power(m)

  energy += P * dt

  power_history.append(P)
  time.append(t)

T_total = steps * dt
P_avg = energy / T_total

print("Total Energy (J):", energy)
print("Average Power (W):", P_avg)

import matplotlib.pyplot as plt

plt.figure()
plt.plot(time, power_history)
plt.xlabel("Time (s)")
plt.ylabel("Power (W)")
plt.title("Power Consumption Over Time")
plt.show()

